"""Deterministic generated documentation contracts for the rule catalog."""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path, PurePosixPath

import pytest

from rtl_lens.knowledge.docs import render_rule_docs, write_rule_docs
from rtl_lens.knowledge.store import TARGET_RULE_IDS, KnowledgeStore

GENERATED_MARKER = "<!-- Generated by RTL Lens; do not edit. -->"


def test_committed_rule_docs_match_typed_catalog() -> None:
    expected = render_rule_docs(KnowledgeStore.load_default())

    assert set(expected) == {
        PurePosixPath("index.md"),
        *(PurePosixPath(f"{rule_id}.md") for rule_id in TARGET_RULE_IDS),
    }
    for relative, content in expected.items():
        assert (Path("docs/rules") / relative).read_text(encoding="utf-8") == content


def test_every_rule_page_contains_bilingual_evidence_and_examples() -> None:
    store = KnowledgeStore.load_default()
    rendered = render_rule_docs(store)

    for entry in store.entries:
        page = rendered[PurePosixPath(f"{entry.rule_id}.md")]
        assert entry.en.title in page
        assert entry.zh_cn.title in page
        for heading in (
            "## English",
            "### Cause",
            "### Risk",
            "### Fix",
            "## 简体中文",
            "### 原因",
            "### 风险",
            "### 修复",
            "## Failing example / 问题示例",
            "## Fixed example / 修复示例",
            "## Native mappings / 原生诊断映射",
            "## References / 参考资料",
        ):
            assert heading in page
        assert page.count("```systemverilog") == 2
        assert all(reference in page for reference in entry.references)
        assert ("No active mapping" in page) == (not entry.engine_mappings)


def test_renderer_is_sorted_and_uses_one_trailing_lf() -> None:
    rendered = render_rule_docs(KnowledgeStore.load_default())

    assert tuple(rendered) == (
        PurePosixPath("index.md"),
        *(PurePosixPath(f"{rule_id}.md") for rule_id in sorted(TARGET_RULE_IDS)),
    )
    assert all(
        content.endswith("\n") and not content.endswith("\n\n") for content in rendered.values()
    )
    assert all("\r" not in content for content in rendered.values())
    assert all(content.startswith(f"{GENERATED_MARKER}\n") for content in rendered.values())


def test_writer_check_mode_detects_drift_without_mutating(tmp_path: Path) -> None:
    output = tmp_path / "rules"
    written = write_rule_docs(output, check=False)
    assert len(written) == 31
    assert write_rule_docs(output, check=True) == written

    stale = output / "index.md"
    stale.write_text(f"{GENERATED_MARKER}\nstale\n", encoding="utf-8")
    before = stale.read_bytes()
    with pytest.raises(RuntimeError, match="stale"):
        write_rule_docs(output, check=True)
    assert stale.read_bytes() == before

    write_rule_docs(output, check=False)
    handwritten = output / "notes.md"
    handwritten.write_text("handwritten\n", encoding="utf-8")
    assert write_rule_docs(output, check=True) == written
    assert handwritten.read_text(encoding="utf-8") == "handwritten\n"

    extra = output / "old-generated.md"
    extra.write_text(f"{GENERATED_MARKER}\nold\n", encoding="utf-8")
    with pytest.raises(RuntimeError, match="extra"):
        write_rule_docs(output, check=True)
    assert extra.read_text(encoding="utf-8") == f"{GENERATED_MARKER}\nold\n"


def test_writer_removes_only_extra_markdown_inside_output(tmp_path: Path) -> None:
    output = tmp_path / "rules"
    output.mkdir(parents=True)
    extra_markdown = output / "old-generated.md"
    handwritten = output / "notes.md"
    unrelated = output / "keep.txt"
    nested = output / "nested" / "keep.md"
    extra_markdown.write_text(f"{GENERATED_MARKER}\nold\n", encoding="utf-8")
    handwritten.write_text("handwritten\n", encoding="utf-8")
    unrelated.write_text("keep\n", encoding="utf-8")
    nested.parent.mkdir()
    nested.write_text("keep\n", encoding="utf-8")

    write_rule_docs(output, check=False)

    assert not extra_markdown.exists()
    assert handwritten.read_text(encoding="utf-8") == "handwritten\n"
    assert unrelated.read_text(encoding="utf-8") == "keep\n"
    assert nested.read_text(encoding="utf-8") == "keep\n"


def test_writer_refuses_to_overwrite_unmanaged_expected_page(tmp_path: Path) -> None:
    output = tmp_path / "rules"
    output.mkdir(parents=True)
    handwritten_index = output / "index.md"
    handwritten_index.write_text("handwritten\n", encoding="utf-8")

    with pytest.raises(RuntimeError, match="unmanaged"):
        write_rule_docs(output, check=False)
    assert handwritten_index.read_text(encoding="utf-8") == "handwritten\n"


def test_cli_rejects_arbitrary_output_and_is_cwd_independent(tmp_path: Path) -> None:
    script = Path(__file__).parents[2] / "tools" / "generate_rule_docs.py"
    rejected = subprocess.run(
        [sys.executable, str(script), "--output", str(tmp_path)],
        cwd=tmp_path,
        check=False,
        capture_output=True,
        text=True,
    )
    assert rejected.returncode == 2
    assert "unrecognized arguments: --output" in rejected.stderr

    checked = subprocess.run(
        [sys.executable, str(script), "--check"],
        cwd=tmp_path,
        check=False,
        capture_output=True,
        text=True,
    )
    assert checked.returncode == 0, checked.stderr
    assert "verified 31 rule documentation files" in checked.stdout
