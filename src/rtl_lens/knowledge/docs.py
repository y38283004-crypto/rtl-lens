"""Deterministic Markdown rendering for the reviewed rule catalog."""

from __future__ import annotations

from collections.abc import Mapping
from importlib import resources
from pathlib import Path, PurePosixPath
from types import MappingProxyType

from rtl_lens.knowledge.schema import ExplanationEntry
from rtl_lens.knowledge.store import KnowledgeStore

GENERATED_MARKER = "<!-- Generated by RTL Lens; do not edit. -->"


def render_rule_docs(store: KnowledgeStore) -> Mapping[PurePosixPath, str]:
    """Render an immutable, path-keyed catalog without writing to disk."""
    entries = tuple(sorted(store.entries, key=lambda entry: entry.rule_id))
    rendered: dict[PurePosixPath, str] = {PurePosixPath("index.md"): _render_index(entries)}
    for entry in entries:
        rendered[PurePosixPath(f"{entry.rule_id}.md")] = _render_entry(entry)
    return MappingProxyType(rendered)


def write_rule_docs(output: Path, *, check: bool) -> tuple[Path, ...]:
    """Write generated docs, or fail without mutation when they have drifted."""
    if output.is_symlink() or (output.exists() and not output.is_dir()):
        raise RuntimeError(f"unmanaged generated rule docs output: {output}")
    rendered = render_rule_docs(KnowledgeStore.load_default())
    destinations = tuple(output.joinpath(*relative.parts) for relative in rendered)
    expected = set(destinations)
    existing = set(output.glob("*.md")) if output.is_dir() else set()
    extra = sorted(path for path in existing - expected if _has_generated_marker(path))
    unmanaged = [
        path
        for path in destinations
        if (path.exists() or path.is_symlink()) and not _is_managed_destination(path)
    ]
    if unmanaged:
        names = ", ".join(path.name for path in unmanaged)
        raise RuntimeError(f"unmanaged generated rule docs destination: {names}")
    missing = [path for path in destinations if not path.is_file()]
    stale = [
        path
        for path, content in zip(destinations, rendered.values(), strict=True)
        if path.is_file() and path.read_bytes() != content.encode("utf-8")
    ]

    if check:
        problems = _drift_summary(missing=missing, stale=stale, extra=extra)
        if problems:
            raise RuntimeError(f"stale generated rule docs: {problems}")
        return destinations

    output.mkdir(parents=True, exist_ok=True)
    for path, content in zip(destinations, rendered.values(), strict=True):
        path.write_bytes(content.encode("utf-8"))
    for path in extra:
        path.unlink()
    return destinations


def _render_index(entries: tuple[ExplanationEntry, ...]) -> str:
    lines = [
        "# RTL Lens diagnostic guides / RTL Lens 诊断指南",
        "",
        (
            "This index is generated from the validated bilingual knowledge store. "
            "Do not edit generated pages by hand."
        ),
        "",
        "本索引由经过校验的双语知识库生成，请勿手工修改生成页面。",
        "",
        "| Rule ID | Severity | English | 简体中文 |",
        "| --- | --- | --- | --- |",
    ]
    lines.extend(
        f"| [`{entry.rule_id}`]({entry.rule_id}.md) | `{entry.severity}` | "
        f"{entry.en.title} | {entry.zh_cn.title} |"
        for entry in entries
    )
    return _document(lines)


def _render_entry(entry: ExplanationEntry) -> str:
    failing = _read_example(entry.failing_example)
    fixed = _read_example(entry.fixed_example)
    lines = [
        f"# `{entry.rule_id}`: {entry.en.title} / {entry.zh_cn.title}",
        "",
        f"**Severity / 严重程度:** `{entry.severity}`",
        "",
        "## English",
        "",
        "### Cause",
        "",
        entry.en.cause,
        "",
        "### Risk",
        "",
        entry.en.risk,
        "",
        "### Fix",
        "",
        entry.en.fix,
        "",
        "## 简体中文",
        "",
        "### 原因",
        "",
        entry.zh_cn.cause,
        "",
        "### 风险",
        "",
        entry.zh_cn.risk,
        "",
        "### 修复",
        "",
        entry.zh_cn.fix,
        "",
        "## Failing example / 问题示例",
        "",
        "```systemverilog",
        failing,
        "```",
        "",
        "## Fixed example / 修复示例",
        "",
        "```systemverilog",
        fixed,
        "```",
        "",
        "## Native mappings / 原生诊断映射",
        "",
    ]
    if entry.engine_mappings:
        lines.extend(
            f"- `{mapping.engine}:{mapping.code}` — `{mapping.verification}` verification"
            for mapping in entry.engine_mappings
        )
    else:
        lines.append("- No active mapping / 暂无活动映射")
        if entry.mapping_note is not None:
            lines.extend(("", entry.mapping_note))
    lines.extend(("", "## References / 参考资料", ""))
    lines.extend(f"- <{reference}>" for reference in entry.references)
    return _document(lines)


def _read_example(relative_path: str) -> str:
    resource = resources.files("rtl_lens.knowledge").joinpath(
        "examples", *PurePosixPath(relative_path).parts
    )
    return _normalize_lf(resource.read_text(encoding="utf-8")).rstrip("\n")


def _document(lines: list[str]) -> str:
    body = "\n".join(lines).rstrip("\n")
    return f"{GENERATED_MARKER}\n{body}\n"


def _normalize_lf(value: str) -> str:
    return value.replace("\r\n", "\n").replace("\r", "\n")


def _has_generated_marker(path: Path) -> bool:
    if path.is_symlink() or not path.is_file():
        return False
    with path.open("r", encoding="utf-8", newline=None) as handle:
        return handle.readline().rstrip("\r\n") == GENERATED_MARKER


def _is_managed_destination(path: Path) -> bool:
    if path.is_symlink() or not path.is_file():
        return False
    return _has_generated_marker(path)


def _drift_summary(*, missing: list[Path], stale: list[Path], extra: list[Path]) -> str:
    groups = (
        ("missing", missing),
        ("stale", stale),
        ("extra", extra),
    )
    return "; ".join(
        f"{label}: {', '.join(path.name for path in paths)}" for label, paths in groups if paths
    )
